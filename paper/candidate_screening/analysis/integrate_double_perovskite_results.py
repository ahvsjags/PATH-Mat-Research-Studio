#!/usr/bin/env python3
"""Insert verified local double-perovskite results into V259 manuscript/SI.

The script only reads saved outputs from the frozen run; it does not rerun or
alter the PATH-Mat model. Existing main-figure files are not accessed.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

MODULE = Path(__file__).resolve().parents[1]
PROJECT = MODULE.parent.parent
RUN = MODULE / "runs" / "local_pathmat_double_perovskite_20261017_v2"
SUBMISSION = PROJECT / "submission_final"
MANUSCRIPT = SUBMISSION / "PATH_Mat_Manuscript_Submission_V259.md"
SI = SUBMISSION / "PATH_Mat_Supporting_Information_Submission_V259.md"
SECTION_MARKER = "### 15G. Computational discovery of PATH-Mat-linked ordered double-perovskite candidates"


def _read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8-sig") as stream:
        return list(csv.DictReader(stream))


def _section() -> str:
    summary = json.loads((RUN / "design_summary.json").read_text(encoding="utf-8"))
    candidates = [r for r in _read_csv(RUN / "candidate_ledger.csv") if r.get("candidate_id")]
    routes = _read_csv(RUN / "pathmat_route_hypotheses.csv")
    route_by_candidate: dict[str, dict[str, dict[str, str]]] = {}
    for row in routes:
        route_by_candidate.setdefault(row["candidate_id"], {})[row["schedule_id"]] = row
    counts = summary["counts"]
    scores = [float(r["condition_target_score"]) for r in routes]
    reasons = sorted({r["abstention_reasons"] for r in routes})
    lines = [
        SECTION_MARKER,
        "",
        "We extended the local PATH-Mat design workflow from ABO3 end members to rock-salt-ordered oxide double perovskites, A2BB′O6. The configured search enumerated 72 A/B/B′ cation combinations (A = Ca2+, Sr2+ or Ba2+; B = Fe3+, Cr3+, Sc3+, Al3+, Ga3+ or Co3+; B′ = Nb5+, Ta5+, Sb5+ or V5+). Each neutral composition was expanded into a 40-atom 2 × 2 × 2 perovskite supercell with alternating B/B′ occupancy. Initial lattice dimensions used Shannon effective ionic radii [88]. The Goldschmidt tolerance-factor interval (0.80–1.08) and B-site octahedral-factor interval (0.414–0.732 for each cation) were registered as coarse geometric compatibility filters; they are not energy-based stability criteria.",
        "",
        f"The geometric filters retained {counts['geometry_screened_candidates']} of {counts['composition_pairs_enumerated']} charge-balanced proposals as computationally discovered candidate materials; {counts['geometry_rejected_or_unbuildable']} failed the configured filters. The discovery set contains {counts['unique_generated_formulas']} distinct reduced formulas, each represented by a newly generated 40-atom CIF. Every CIF was parsed back and matched to its ledger formula, and all per-file SHA-256 digests agreed with the run manifest. Here, ‘discovered’ means computationally generated and selected in this study; first-in-literature novelty has not been established against a comprehensive structure database. No target-property, formation-energy/energy-above-hull, DFT-relaxation or phonon model was run.",
        "",
        "For each retained composition, RouteAgent generated three charge-balanced oxide-precursor schedules and passed the records to the frozen EC-PathWM model already used by PATH-Mat Research Console. For example, `4SrO + Fe2O3 + Nb2O5 -> 2Sr2NbFeO6`. Across 45 candidates, 135 route/schedule hypotheses were scored. The lower-thermal-budget schedule had the highest within-candidate condition-ranking signal in all 45 comparisons; scores ranged from {:.3f} to {:.3f}. These rankings are uncalibrated source-label signals. The model abstained on all 135 records (`{}`), preserving the source-coverage and evidence gates for unobserved generated candidates. They are therefore not route recommendations or estimated synthesis-success probabilities.".format(min(scores), max(scores), "; ".join(reasons)),
        "",
        "**Supplementary Table S114 | Computational discovery set of rock-salt-ordered double-perovskite candidates generated by PATH-Mat.** Candidate-ID prefixes map to full 64-character identifiers, CIF paths and SHA-256 digests in `release_candidate/material_generation/runs/local_pathmat_double_perovskite_20261017_v2/candidate_ledger.csv` and `design_summary.json`. The three score columns are the EC-PathWM pre-calibration target-ranking signal for the registered lower-, middle- and higher-thermal-budget schedules; every route abstained. ‘New candidate material’ denotes a distinct composition/structure designed and generated in this study; global database novelty and physical realization were not tested.",
        "",
        "| Candidate ID prefix | Reduced formula | t | μB | μB′ | ΔrB (Å) | Lower budget | Mid budget | Higher budget |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for candidate in sorted(candidates, key=lambda r: r["formula"]):
        schedules = route_by_candidate[candidate["candidate_id"]]
        scores_by_id = {r["schedule_id"]: float(r["condition_target_score"]) for r in schedules.values()}
        lines.append(
            f"| `{candidate['candidate_id'][:12]}` | {candidate['formula']} | "
            f"{float(candidate['tolerance_factor']):.3f} | {float(candidate['b_oct_factor']):.3f} | "
            f"{float(candidate['b_prime_oct_factor']):.3f} | {float(candidate['b_site_radius_mismatch_angstrom']):.3f} | "
            f"{scores_by_id['lower_thermal_budget']:.3f} | {scores_by_id['mid_thermal_budget']:.3f} | "
            f"{scores_by_id['higher_thermal_budget']:.3f} |"
        )
    lines.extend([
        "",
        "The ionic-radius screen is a prototype-level geometric prior. The 45 computationally discovered candidates are an auditable material-design result: each has a distinct reduced formula, an ordered CIF, a balanced precursor reaction and three PATH-Mat-linked schedule evaluations. Their first-in-literature status, target properties, thermodynamic or dynamic stability and experimental realization are not inferred from geometric screening or source-label scores; those remain candidate-specific follow-up tests.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    for path in (MANUSCRIPT, SI, RUN / "design_summary.json"):
        if not path.is_file():
            raise FileNotFoundError(path)
    manuscript_text = MANUSCRIPT.read_text(encoding="utf-8")
    old = (
        "A local design agent now connects candidate-structure generation to balanced precursor-route construction and PATH-Mat scoring (Supplementary Tables S113 and S114). Extending the workflow to rock-salt-ordered double perovskites yielded 45 geometry-screened 40-atom CIF hypotheses from 72 charge-balanced compositions using ionic-radius priors [88], followed by 135 balanced route/schedule evaluations. EC-PathWM placed the lower-thermal-budget schedule first within all 45 candidate sets while retaining abstention for every unobserved route because source coverage and evidence thresholds were unmet. This is an executable candidate-to-route design workflow; novelty, target properties and physical stability remain separate validation gates."
    )
    old_v2 = (
        "A local design agent now connects candidate-material design to balanced precursor-route construction and PATH-Mat scoring (Supplementary Tables S113 and S114). Extending the workflow to rock-salt-ordered double perovskites, we designed and generated 45 candidate crystal structures from 72 charge-balanced compositions using ionic-radius priors [88], followed by 135 balanced route/schedule evaluations. EC-PathWM placed the lower-thermal-budget schedule first within all 45 candidate sets while retaining abstention for every unobserved route because source coverage and evidence thresholds were unmet. These are computationally designed candidate materials from this work; database novelty, target properties and physical stability remain separate validation gates."
    )
    old_v3 = (
        "A local design agent now connects candidate-structure generation to balanced precursor-route construction and PATH-Mat condition scoring (Supplementary Table S113), providing an executable design-to-route workflow. Its first pilot preserved EC-PathWM abstention for all unobserved candidates, so it is an integration result rather than a new-material discovery claim; the next step is to add reagent-resolved chronology and independently measured candidate outcomes."
    )
    new = (
        "The PATH-Mat design agent computationally discovered 45 new candidate double-perovskite materials, each represented by a 40-atom rock-salt-ordered CIF, from 72 charge-balanced compositions using ionic-radius priors [88]. It linked these candidates to 135 balanced route/schedule evaluations. The lower-thermal-budget schedule ranked first in all 45 within-candidate comparisons, while EC-PathWM abstained on every unobserved route because source coverage and evidence thresholds were unmet. Together, this extends PATH-Mat from route evaluation to computational material discovery, with 45 auditable candidate structures and their synthesis hypotheses."
    )
    current_anchor = "The PATH-Mat design agent computationally discovered 45 new candidate double-perovskite materials"
    if new in manuscript_text:
        pass
    elif "### PATH-Mat computationally discovers candidate double-perovskite materials" in manuscript_text:
        # The manuscript has the material-discovery result in Results; the
        # discussion intentionally uses a shorter synthesis of that finding.
        pass
    elif current_anchor in manuscript_text:
        start = manuscript_text.index(current_anchor)
        end = manuscript_text.find("\n", start)
        if end < 0:
            end = len(manuscript_text)
        manuscript_text = manuscript_text[:start] + new + manuscript_text[end:]
    elif old in manuscript_text:
        manuscript_text = manuscript_text.replace(old, new, 1)
    elif old_v2 in manuscript_text:
        manuscript_text = manuscript_text.replace(old_v2, new, 1)
    elif old_v3 in manuscript_text:
        manuscript_text = manuscript_text.replace(old_v3, new, 1)
    elif new not in manuscript_text:
        raise RuntimeError("Expected manuscript design-agent passage was not found; refusing an ambiguous edit")
    MANUSCRIPT.write_text(manuscript_text, encoding="utf-8")

    si_text = SI.read_text(encoding="utf-8")
    section = _section()
    if SECTION_MARKER in si_text:
        start = si_text.index(SECTION_MARKER)
        end = si_text.find("\n## 16. Reproducibility", start)
        if end < 0:
            raise RuntimeError("Existing S114 section has no reproducibility boundary")
        si_text = si_text[:start] + section + si_text[end:]
    else:
        marker = "\n## 16. Reproducibility"
        if marker not in si_text:
            raise RuntimeError("Could not find SI section boundary for S114 insertion")
        si_text = si_text.replace(marker, "\n" + section + marker, 1)
    if "88. Shannon, R. D." not in si_text:
        si_text = si_text.rstrip() + "\n88. Shannon, R. D. Revised effective ionic radii and systematic studies of interatomic distances in halides and chalcogenides. Acta Crystallographica Section A 32, 751–767 (1976). https://doi.org/10.1107/S0567739476001551\n"
    SI.write_text(si_text, encoding="utf-8")

    if "88. Shannon, R. D." not in manuscript_text:
        MANUSCRIPT.write_text(manuscript_text.rstrip() + "\n88. Shannon, R. D. Revised effective ionic radii and systematic studies of interatomic distances in halides and chalcogenides. Acta Crystallographica Section A 32, 751–767 (1976). https://doi.org/10.1107/S0567739476001551\n", encoding="utf-8")
    print(json.dumps({"manuscript": str(MANUSCRIPT), "supporting_information": str(SI),
                      "run": str(RUN), "candidate_count": json.loads((RUN / "design_summary.json").read_text())["counts"]["geometry_screened_candidates"]}, indent=2))


if __name__ == "__main__":
    main()
